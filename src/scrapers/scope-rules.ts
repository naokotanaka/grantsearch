/**
 * 分野・地域の決まりによる除外（AIの判断に任せない確定的な規則）
 */

/**
 * 助成元が長久手市以外の市区町村（役所・役場・社協・社会福祉協議会）か。
 * 市区町村の助成は、ページに書いていなくてもその市区町村の住民・団体限定なので、
 * AI読み取りが「要確認」を返しても掲載しない。
 * 都道府県（愛知県 等）や、市名を含むだけの財団・企業（例:「名古屋銀行」）は対象外にしない。
 */
export function isOtherMunicipality(organization: string): boolean {
  const org = organization.replace(/[\s　]/g, "").replace(/（.*?）|\(.*?\)/g, "");
  if (!org || /長久手/.test(org)) return false;
  // 例:「名古屋市」「名古屋市社協」「日進市社会福祉協議会」「東郷町役場」「瀬戸市子ども政策課」
  return /^[^、・/／]{1,10}?(市|区|町|村)(社協|社会福祉協議会|役所|役場|教育委員会|[^、・/／]{0,8}課)?$/.test(
    org,
  );
}
